-- Run once in Supabase SQL Editor. Dedicated schema is not exposed through the
-- public Data API; clients access data only through the authenticated server.
CREATE SCHEMA IF NOT EXISTS raffle;
REVOKE ALL ON SCHEMA raffle FROM PUBLIC;
SET LOCAL search_path = raffle, pg_catalog;
CREATE TABLE IF NOT EXISTS settings(id INTEGER PRIMARY KEY CHECK(id=1),is_open INTEGER NOT NULL DEFAULT 0,view TEXT NOT NULL DEFAULT 'waiting',rank INTEGER NOT NULL DEFAULT 4);
INSERT INTO settings(id) VALUES(1) ON CONFLICT DO NOTHING;
CREATE TABLE IF NOT EXISTS entries(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,nickname TEXT NOT NULL,phone_hash TEXT NOT NULL UNIQUE,ending TEXT NOT NULL,receipt_hash TEXT NOT NULL UNIQUE,created DOUBLE PRECISION NOT NULL);
CREATE TABLE IF NOT EXISTS draws(rank INTEGER PRIMARY KEY CHECK(rank BETWEEN 1 AND 4),created DOUBLE PRECISION NOT NULL);
CREATE TABLE IF NOT EXISTS winners(entry_id BIGINT PRIMARY KEY REFERENCES entries(id),rank INTEGER NOT NULL REFERENCES draws(rank),position INTEGER NOT NULL,UNIQUE(rank,position));
CREATE TABLE IF NOT EXISTS prizes(rank INTEGER PRIMARY KEY CHECK(rank BETWEEN 1 AND 4),name TEXT NOT NULL DEFAULT '상품 미정');
INSERT INTO prizes(rank) VALUES(1),(2),(3),(4) ON CONFLICT DO NOTHING;
CREATE TABLE IF NOT EXISTS sessions(token_hash TEXT PRIMARY KEY,csrf TEXT NOT NULL,expires DOUBLE PRECISION NOT NULL);
CREATE TABLE IF NOT EXISTS attempts(ip_hash TEXT PRIMARY KEY,count INTEGER NOT NULL,until DOUBLE PRECISION NOT NULL);
CREATE TABLE IF NOT EXISTS audit(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,action TEXT NOT NULL,created DOUBLE PRECISION NOT NULL);
REVOKE ALL ON ALL TABLES IN SCHEMA raffle FROM PUBLIC;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA raffle FROM PUBLIC;
ALTER TABLE settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE entries ENABLE ROW LEVEL SECURITY;
ALTER TABLE draws ENABLE ROW LEVEL SECURITY;
ALTER TABLE winners ENABLE ROW LEVEL SECURITY;
ALTER TABLE prizes ENABLE ROW LEVEL SECURITY;
ALTER TABLE sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE attempts ENABLE ROW LEVEL SECURITY;
ALTER TABLE audit ENABLE ROW LEVEL SECURITY;
